HEADERS = {"User-Agent": "OpenData"}        # рядок має бути ТОЧНО таким, інакше API віддає звичайну картку

# рекомендована пауза між запитами до OpenData API — 5-7с (readme порталу)
_MIN_INTERVAL = 6.0
_last_request = 0.0


def _pace() -> None:
    global _last_request
    wait = _MIN_INTERVAL - (time.time() - _last_request)
    if wait > 0:
        time.sleep(wait)
    _last_request = time.time()


def _get(url: str):
    _pace()
    resp = httpx.get(url, headers=HEADERS, follow_redirects=True, timeout=30)
    resp.raise_for_status()
    return resp


def _q(nreg: str) -> str:
    """URL-кодування ідентифікатора документа (може містити кирилицю й '/', напр.
    254к/96-вр) — '/' навмисно НЕ кодуємо: сервер очікує його буквально."""
    return urllib.parse.quote(nreg, safe="/")


def _fmt_date(yyyymmdd) -> str | None:
    """20260412 -> '12.04.2026'. Деякі дати — умовні маркери в майбутньому
    (рік 3000 = "набере чинності за певних умов, дата ще не настала")."""
    if not yyyymmdd:
        return None
    s = str(yyyymmdd)
    if len(s) != 8:
        return s
    y, m, d = s[:4], s[4:6], s[6:8]
    if y == "3000":
        return f"умовна дата (ще не настала), {d}.{m}"
    return f"{d}.{m}.{y}"


