_SECTION_ARABIC_RE = re.compile(r"^\d+[¹²³]*\.\s*[A-ZА-ЯІЇЄҐ][A-ZА-ЯІЇЄҐ \-,'’]{3,}\*{0,3}$")  # ПДР
# У джерелі римські цифри інколи мішають кирилицю й латину (однаковий
# вигляд, різний Unicode: "VІ" — латинська V + кириличне І) — очевидний
# артефакт старого OCR/конвертації документа. Приймаємо обидва варіанти.
_ROMAN_CYR2LAT = str.maketrans({"І": "I", "Х": "X", "С": "C", "М": "M"})

# ключові слова — case-insensitive: деякі кодекси пишуть заголовки
# суцільно ВЕЛИКИМИ ("РОЗДІЛ I." замість "Розділ I."), Податковий кодекс —
# реальний приклад
_SECTION_ROMAN_RE = re.compile(r"^Розділ\s+([IVXLCDMІХСМ]+)\.?\s+\S", re.IGNORECASE)              # code
_CHAPTER_RE = re.compile(r"^Глава\s+([\dIVXLCDMІХСМ]+)\.?\s+\S", re.IGNORECASE)   # code; здебільшого
# арабські, але є винятки без окремого Розділу — глава римськими (КЗпП: "Глава I")
_ARTICLE_RE = re.compile(r"^Стаття\s+(\d+[¹²³]*)\s*\.", re.IGNORECASE)   # інколи зайвий пробіл: "Стаття 168 ."
_PDR_POINT_RE = re.compile(r"^(\d{1,3}\.\d{1,3})\.\s")     # "12.4. " (ПДР: розділ.пункт)
_PART_RE = re.compile(r"^(\d{1,2})\.\s")                    # "1. "  (частина статті)
_LAW_POINT_RE = re.compile(r"^(\d{1,3})\)\s")               # "1) "  (пункт частини)
_SUBPOINT_RE = re.compile(r"^[а-щьюяіїєґ]\)\s")             # "а) "  (підпункт)
_NOISE_RE = re.compile(r"^\{.*\}$", re.DOTALL)              # виноски "{Стаття... зі змінами...}"
# "Прикінцеві та перехідні положення" часто містять дослівний текст статей
# ІНШОГО закону (поправка виду "доповнити Земельний кодекс статтею 204
# такого змісту: ..."). Структурно ці абзаци нічим не відрізняються від
# справжніх заголовків — реальні випадки: Про акціонерні товариства
# (вставка в закон про ТОВ/ТДВ), Про Державний земельний кадастр (вставка
# в Земельний кодекс, "Стаття 204" замість власних ~44 статей документа).
# Тому після заходу в цей розділ більше не оновлюємо article/section за
# новими "Стаття N." — вони, найімовірніше, чужі.
#
# Якір на початку рядка (не search() будь-де в реченні!) — інакше фальшиво
# спрацьовує на преамбулах, які просто ЗГАДУЮТЬ цю секцію мимохідь. Реальний
# випадок: "Про ветеринарну медицину та благополуччя тварин" (1206-20) —
# перед Розділом I стоїть виноска-примітка "{У тексті Закону (крім розділу
# XV "Прикінцеві та перехідні положення"): ...}" — вона згадує назву секції
# в дужках, а не є нею, але коротка (<100 симв. до крапки з іменем) і
# раніше проходила search(). Через якір "^" ця примітка більше не збігається
# (починається з "{", а не з "Розділ"/"Стаття"/номера) — стан in_final не
# вмикається завчасно й не "з'їдає" всі статті аж до кінця документа.
_FINAL_PROVISIONS_RE = re.compile(
    r"^(?:(?:Розділ|Стаття)\s+)?(?:[\dIVXLCDMІХСМ]+[¹²³]*\.?\s*)?"
    r"Прикінцеві\s*(?:(?:та|і)\s*перехідні\s*)?положення", re.IGNORECASE,
)
_FINAL_PROVISIONS_MAXLEN = 100   # це має бути короткий заголовок, не згадка посеред речення


def fetch_card(doc: dict) -> dict:
    """Картка документа з офіційного API — статус, дати, номер акта,
    підстава поточної редакції. Легкий запит, для watch.py."""
    r = _get(f"{API_BASE}/laws/card/{_q(doc['id'])}.json")
    d = r.json()
    return {
        "id": doc["id"], "title": d.get("nazva") or doc["title"], "doc_type": doc["doc_type"],
        "structure": doc["structure"],
        "source_url": f"{SHOW_BASE}/laws/show/{_q(doc['id'])}",
        "act_number": d.get("n_vlas") or d.get("orgnum"),
        "status_code": d.get("status"),
        "adopted_date": _fmt_date(d.get("orgdat") or d.get("pridat")),
        "revision_date": _fmt_date(d.get("poddat") or d.get("datred")),
        "revision_basis": d.get("pidstava"),
        "last_checked_at": datetime.datetime.now().isoformat(timespec="seconds"),
    }


def _paragraphs(html: str) -> list[tuple[str, str | None]]:
    """(текст, anchor) для кожного змістовного <p> — виноски-примітки відкинуті."""
    soup = BeautifulSoup(html, "html.parser")
    out = []
    for p in soup.find_all("p"):
        if p.find_parent("em"):
            continue
        text = p.get_text(" ", strip=True)
        if not text or _NOISE_RE.match(text):
            continue
        anchor_tag = p.find("a", attrs={"name": True})
        out.append((text, anchor_tag["name"] if anchor_tag else None))
    return out


def fetch_clauses(doc: dict) -> list[dict]:
    """Повний текст, розрізаний на клаузи за реальною юридичною структурою.
    Кожен рядок успадковує розділ/главу/статтю/частину від останнього
    відповідного заголовка вище по тексту."""
    html = _get(f"{API_BASE}/laws/show/{_q(doc['id'])}").text
    structure = doc["structure"]
    section = chapter = article = part = point = None
    in_final = False
    clauses = []

    for text, anchor in _paragraphs(html):
        if (structure in ("law", "code") and not in_final and len(text) < _FINAL_PROVISIONS_MAXLEN
                and _FINAL_PROVISIONS_RE.match(text)):
            in_final = True
            section = chapter = None
            article, part, point = text, None, None
        elif in_final and structure in ("law", "code"):
            # у Прикінцевих трапляється чужий "Стаття N." (див. коментар
            # біля _FINAL_PROVISIONS_RE) — article/section більше НЕ
            # оновлюємо, лише частина/пункт (нумерація в межах Прикінцевих
            # цілком реальна і своя)
            if _PART_RE.match(text) and len(text) < 400:
                part, point = _PART_RE.match(text).group(1), None
            elif m := _LAW_POINT_RE.match(text):
                point = m.group(1)
        elif structure == "pdr" and _SECTION_ARABIC_RE.match(text):
            section, point = text, None
        elif structure == "code" and _SECTION_ROMAN_RE.match(text):
            section, chapter, article, part, point = text, None, None, None, None
        elif structure == "code" and _CHAPTER_RE.match(text):
            chapter, article, part, point = text, None, None, None
        elif structure in ("law", "code") and _ARTICLE_RE.match(text):
            article, part, point = text, None, None
        elif structure == "pdr" and (m := _PDR_POINT_RE.match(text)):
            point = m.group(1)
        elif structure in ("law", "code") and _PART_RE.match(text) and len(text) < 400:
            part, point = _PART_RE.match(text).group(1), None
        elif structure in ("law", "code") and (m := _LAW_POINT_RE.match(text)):
            point = m.group(1)

        clauses.append({
            "document_id": doc["id"], "section": section, "chapter": chapter, "article": article,
            "part": part, "point": point, "subpoint": None,
            "text": text, "anchor": f"#{anchor}" if anchor else None, "qdrant_id": None,
        })
    return clauses


def group_for_embedding(clauses: list[dict], structure: str) -> list[dict]:
    """SQLite тримає кожен абзац окремо (точні якорі/аудит); для retrieval
    занадто дрібно — перелік підстав розсипається на окремі чанки і
    втрачає повноту. Групуємо назад у змістовно завершену одиницю:
    law/code — усі пункти однієї частини статті разом; pdr — усі
    підпункти одного пункту разом."""
    key_fn = ((lambda c: (c["article"], c["part"])) if structure in ("law", "code")
             else (lambda c: (c["section"], c["point"])))
    groups: dict[tuple, dict] = {}
    order = []
    for c in clauses:
        key = key_fn(c)
        if key not in groups:
            groups[key] = dict(c)
            order.append(key)
        else:
            groups[key]["text"] += "\n" + c["text"]
            groups[key]["anchor"] = groups[key]["anchor"] or c["anchor"]
    return [groups[k] for k in order]


def cite(clause: dict, doc_title: str) -> str:
    """Людське посилання з метаданих клаузи: «ККУ, ст. 185, ч. 1» чи
    «ПДР, розділ 12, п. 12.4»."""
    bits = [doc_title]
    if clause.get("article"):
        num = _ARTICLE_RE.match(clause["article"])
        bits.append(f"ст. {num.group(1)}" if num else clause["article"])
    if clause.get("chapter") and not clause.get("article"):
        m = _CHAPTER_RE.match(clause["chapter"])
        bits.append(f"глава {m.group(1)}" if m else clause["chapter"])
    if clause.get("section") and not clause.get("article") and not clause.get("chapter") \
            and not clause.get("point"):
        m_rm = _SECTION_ROMAN_RE.match(clause["section"])
        if m_rm:
            bits.append(f"розділ {m_rm.group(1).translate(_ROMAN_CYR2LAT)}")
        else:
            num, _, name = clause["section"].partition(".")
            bits.append(f"розділ {num.strip()} ({name.strip()})" if name.strip() else f"розділ {num.strip()}")
    if clause.get("part"):
        bits.append(f"ч. {clause['part']}")
    if clause.get("point"):
        bits.append(f"п. {clause['point']}")
    return ", ".join(bits)


