def retrieve(query: str, k: int = 3) -> list:
    """Лексичний скоринг: точний збіг слів + часткове (префіксне, від 5 символів)
    співпадіння — щоб ловити словоформи на кшталт «зупинили»/«зупинку»."""
    words = set(query.lower().replace(",", " ").replace(".", " ").replace("?", " ").split())
    scored = []
    for keys, text in KB:
        keywords = keys.split()
        exact = len(words & set(keywords))
        partial = sum(
            1 for w in words for kw in keywords
            if len(w) > 4 and (w.startswith(kw[:5]) or kw.startswith(w[:5]))
        )
        scored.append((exact * 2 + partial, text))
    scored.sort(key=lambda x: -x[0])
    return [t for s, t in scored[:k] if s > 0]


def as_context(query: str, k: int = 3) -> str:
    """Готовий блок для системного промпта. fail-closed: якщо нічого не
    знайшли — повертаємо порожньо, а не найближчий за замовчуванням пункт.
    Порожній контекст + інструкція в BASE_PROMPT змушує модель чесно
    сказати «в базі цього немає» замість підміни випадковим правилом."""
    hits = retrieve(query, k)
    if not hits:
        return ""
    return "\n\nВитяг з бази знань:\n" + "\n---\n".join(hits)
